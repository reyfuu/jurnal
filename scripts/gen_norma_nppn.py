"""Buat internal/tax/norma_data.go dari sheet "Norma" Tax Planning Calculator V2.1 (BSV Consulting),
yang menyalin Lampiran PER-17/PJ/2015 (norma penghitungan penghasilan neto, WP OP).

Pakai: python3 -I scripts/gen_norma_nppn.py "<path>/Tax_Planning_Calculator_V2.1.xlsm"
Hanya membaca XML sheet; makro (vbaProject.bin) tidak disentuh.
Kolom D/E/F = 10 ibukota provinsi / ibukota provinsi lainnya / daerah lainnya.
Sel kosong atau "-" = tidak tersedia (-1), sengaja tidak ditebak.
KLU kembar di workbook: baris pertama dipakai, sisanya dicetak sebagai peringatan untuk dicek tim.
"""
import re
import sys
import zipfile
import xml.etree.ElementTree as ET

OUT = "internal/tax/norma_data.go"
NS = {"m": "http://schemas.openxmlformats.org/spreadsheetml/2006/main"}

z = zipfile.ZipFile(sys.argv[1])
ss = [
    "".join(t.text or "" for t in si.iter("{%s}t" % NS["m"]))
    for si in ET.fromstring(z.read("xl/sharedStrings.xml")).findall("m:si", NS)
]
sheet = ET.fromstring(z.read("xl/worksheets/sheet5.xml"))


def bps(s):
    s = (s or "").strip()
    if s in ("", "-"):
        return -1
    return round(float(s) * 100)


rows = []
for row in sheet.iter("{%s}row" % NS["m"]):
    if int(row.get("r")) < 4:
        continue
    c = {}
    for cell in row.findall("m:c", NS):
        v = cell.find("m:v", NS)
        if v is None:
            continue
        val = v.text
        if cell.get("t") == "s":
            val = ss[int(val)]
        c[re.match(r"[A-Z]+", cell.get("r")).group()] = val
    klu = (c.get("B") or "").strip()
    if not klu:
        continue
    uraian = " ".join((c.get("C") or "").split())
    r = (klu.zfill(5), uraian, bps(c.get("D")), bps(c.get("E")), bps(c.get("F")))
    lama = next((x for x in rows if x[0] == r[0]), None)
    if lama:
        if lama != r:
            print(f"PERINGATAN: KLU {r[0]} kembar, dibuang: {r[1]} (dipakai: {lama[1]})", file=sys.stderr)
        continue
    rows.append(r)

with open(OUT, "w") as f:
    f.write("// Code generated by scripts/gen_norma_nppn.py; DO NOT EDIT.\n")
    f.write("// Sumber: sheet \"Norma\" Tax Planning Calculator V2.1 (BSV Consulting), salinan Lampiran\n")
    f.write("// PER-17/PJ/2015. Basis poin per wilayah: 10 ibukota provinsi, ibukota provinsi lainnya,\n")
    f.write("// daerah lainnya; -1 = tidak tersedia.\n\npackage tax\n\nvar normaBawaan = []Norma{\n")
    for r in rows:
        uraian = r[1].replace("\\", "\\\\").replace('"', '\\"')
        f.write(f'\t{{"{r[0]}", "{uraian}", {r[2]}, {r[3]}, {r[4]}}},\n')
    f.write("}\n")
print(len(rows), "baris")
