"""Buat internal/tax/klu_data.go dari docs/CTTOR dan NPM Nasional.pdf (buku sektoral DJP).

Pakai: python3 scripts/gen_klu_benchmark.py  (butuh pdftotext dari poppler-utils)
"""
import re
import subprocess

PDF = "docs/CTTOR dan NPM Nasional.pdf"
OUT = "internal/tax/klu_data.go"
KECIL = {"dan", "atau", "yang", "di", "dari", "untuk", "dengan", "tanpa", "bukan", "ke", "oleh", "pada", "lainnya", "ytdl", "ybdi"}
SINGKATAN = {"ytdl": "YTDL", "ybdi": "YBDI", "bbm": "BBM", "atm": "ATM"}

text = subprocess.run(["pdftotext", "-layout", PDF, "-"], capture_output=True, text=True, check=True).stdout
pct = r"(-?[\d.]+,\d+)%"


def bps(s):  # "1,27" -> 127 (persen dua desimal -> basis poin)
    return round(float(s.replace(".", "").replace(",", ".")) * 100)


def judul(nama):
    kata = nama.lower().split()
    out = []
    for i, k in enumerate(kata):
        if k in SINGKATAN:
            out.append(SINGKATAN[k])
        elif i > 0 and k in KECIL:
            out.append(k)
        else:
            out.append(k[:1].upper() + k[1:])
    return " ".join(out)


rows = []
for pg in text.split("\f"):
    if "Nasional" not in pg or "CTTOR" not in pg:
        continue
    m = re.search(r"^\s*(\d{3})\s*-\s*(.+?)\s*$", pg, re.M)
    nas = re.search(r"Nasional\s+" + pct + r"\s+" + pct, pg)
    if not (m and nas):
        raise SystemExit("halaman tidak terbaca:\n" + pg[:300])
    rows.append((m.group(1), judul(m.group(2)), bps(nas.group(1)), bps(nas.group(2))))

kodes = [r[0] for r in rows]
assert len(set(kodes)) == len(kodes), "KLU ganda"
with open(OUT, "w") as f:
    f.write("// Code generated by scripts/gen_klu_benchmark.py; DO NOT EDIT.\n")
    f.write("// Sumber: DJP, \"Gambaran Umum Sektoral Kanwil Terhadap Nasional\" (data buku sektoral 2021,\n")
    f.write("// SPT tahun pajak 2020, diperbarui 28 Januari 2022), angka Nasional per kelompok KLU 3 digit.\n\n")
    f.write("package tax\n\nvar KLUBenchmarks = []KLUBenchmark{\n")
    for kode, nama, cttor, npm in rows:
        f.write(f'\t{{"{kode}", "{nama}", {cttor}, {npm}}},\n')
    f.write("}\n")
print(f"{len(rows)} KLU ditulis ke {OUT}")
